# Classify scraped questions into levels based on complexity
def classify_level(q):
    ql = q.lower()
    # Senior indicators
    senior_keywords = ['3-5 year', '5 year', 'board', 'transformation', 'c-suite', 'cfo', 'organization',
                       'enterprise', 'global', 'acquisition', 'ipo', 'merger', 'vision', 'evp',
                       'chief', 'vp of', 'director of', 'head of']
    # Middle indicators
    middle_keywords = ['team', 'budget', 'strategy', 'manage', 'lead', 'mentor', 'cross-functional',
                       'stakeholder', 'vendor', 'agency', 'roadmap', 'portfolio', 'scale',
                       'integrate', 'align', 'optimize', 'attribution', 'framework']
    # Junior indicators
    junior_keywords = ['campaign', 'analyze', 'measure', 'report', 'execute', 'segment',
                       'create', 'develop', 'implement', 'run', 'tool', 'platform',
                       'google analytics', 'a/b test', 'ab test', 'social media', 'email']
    
    # Simple/basic questions = intern/fresher level
    basics = ['what is', 'define', 'meaning', 'difference between', 'explain', 'list']
    
    # Count matches
    senior_score = sum(1 for k in senior_keywords if k in ql)
    middle_score = sum(1 for k in middle_keywords if k in ql) 
    junior_score = sum(1 for k in junior_keywords if k in ql)
    basic_score = sum(1 for k in basics if k in ql[:30])
    
    if basic_score > 0 and senior_score == 0 and middle_score == 0:
        return 'Intern'
    elif junior_score > 0 and middle_score == 0 and senior_score == 0:
        return 'Junior'
    elif middle_score > junior_score and senior_score == 0:
        return 'Middle'
    elif senior_score > 0:
        return 'Senior'
    elif basic_score > 0:
        return 'Fresher'
    elif junior_score > 0:
        return 'Junior'
    else:
        return 'Junior'  # default

