# Clean scraped questions - filter out non-questions and ads
def is_valid_question(q):
    # Remove ads and junk
    skip_phrases = [
        'looking to enhance', 'are you ready to master', 'want to master',
        'want to learn from', 'looking for fresh', 'enrol in upGrad',
        'join upGrad', 'a complete guide to', '5 p\'s of marketing: how to make',
        'what is the smart method', 'how to ace a', 'how to nail a',
        'personal branding: how to build', 'what are competency-based',
        'what is the best answer for', 'what questions should i ask',
        'what\'s a good weakness', 'how to answer why',
        'how to create a personal blog', 'which is the best certification',
        'how long will content', 'how digital marketing helps',
        'what is marketing management', 'can ai-assisted',
        'what are the 8 p'
    ]
    ql = q.lower()
    for sp in skip_phrases:
        if sp in ql:
            return False
    # Must contain a question mark
    if '?' not in q:
        return False
    # Must be reasonable length
    if len(q) < 15 or len(q) > 400:
        return False
    return True

scraped_clean = [q for q in scraped if is_valid_question(q)]
print(f"Valid scraped questions: {len(scraped_clean)}")

